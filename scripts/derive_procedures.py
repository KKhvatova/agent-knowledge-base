"""Write data/derived/procedures.yaml: LLM-derived Procedure assets, frozen as fixtures.

Pipeline step T5 (DESIGN.md §3) turns Knowledge assets into step-by-step Procedures.
In production this runs on Claude via Bedrock. In this POC the procedures below were
written by Claude Code during development from the current source pages, and are
stored with the exact hash of the source version they were derived from (provenance).

If a source page changes, its hash no longer matches: the procedure is invalidated and
must be regenerated (re-run this script after updating the text below).

Usage: uv run python scripts/derive_procedures.py
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / "data" / "sources" / "confluence-hr" / "pages"

PROCEDURES = [
    {
        "id": "procedure:request-vacation-ca",
        "title": "How to request vacation (Canada)",
        "language": "en",
        "derived_from": ["2001"],
        "steps": (
            "1. Check your balance: full-time employees receive 15 days of paid vacation per "
            "year; up to 5 unused days carry over and must be used by March 31.\n"
            "2. Submit the request in Workday at least 2 weeks before the first day off.\n"
            "3. Your manager approves or declines within 3 business days."
        ),
    },
    {
        "id": "procedure:richiedere-ferie-it",
        "title": "Come richiedere le ferie (Italia)",
        "language": "it",
        "derived_from": ["1001"],
        "steps": (
            "1. Verifica il saldo: 26 giorni lavorativi di ferie all'anno, più 104 ore di ROL.\n"
            "2. Inserisci la richiesta nel portale HR Persona; per più di 5 giorni, almeno "
            "15 giorni prima.\n"
            "3. Il responsabile approva o rifiuta entro 3 giorni lavorativi."
        ),
    },
    {
        "id": "procedure:malattia-it",
        "title": "Cosa fare in caso di malattia (Italia)",
        "language": "it",
        "derived_from": ["1002"],
        "steps": (
            "1. Avvisa il responsabile e HR prima dell'inizio dell'orario di lavoro.\n"
            "2. Fatti rilasciare dal medico il certificato telematico INPS.\n"
            "3. Comunica a HR il numero di protocollo del certificato entro 2 giorni."
        ),
    },
    {
        "id": "procedure:submit-expenses",
        "title": "How to submit an expense report",
        "language": "en",
        "derived_from": ["9001"],
        "steps": (
            "1. Upload your receipts to SpendTool.\n"
            "2. Submit the report within 30 days of the expense; meal caps are 40 EUR (Italy), "
            "60 CAD (Canada), 60 USD (United States) per day.\n"
            "3. Your manager approves; Finance reimburses within 10 business days."
        ),
    },
]


def main() -> None:
    out = []
    for proc in PROCEDURES:
        sources = [
            {
                "record": f"confluence-hr:{page}",
                "body_sha256": hashlib.sha256((PAGES / f"{page}.html").read_bytes()).hexdigest(),
            }
            for page in proc["derived_from"]
        ]
        out.append(
            {k: v for k, v in proc.items() if k != "derived_from"} | {"derived_from": sources}
        )
    target = ROOT / "data" / "derived" / "procedures.yaml"
    target.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/derive_procedures.py. LLM-derived Procedure assets (T5).\n"
    target.write_text(header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False))
    print(f"Wrote {len(out)} procedures to {target}")


if __name__ == "__main__":
    main()
